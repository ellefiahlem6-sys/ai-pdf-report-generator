import pandas as pd
from fpdf import FPDF
import smtplib
from email.message import EmailMessage
import os
from dotenv import load_dotenv
from openai import OpenAI

# 1. Setup
load_dotenv()
client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))

SENDER_EMAIL = "ellefiahlem6@gmail.com" # بريدك
APP_PASSWORD = "ubwl gmcp htkv yxqv"    # كلمة مرور التطبيقات (16 حرف)
RECEIVER_EMAIL = "ellefiahlem6@gmail.com" 

# 2. البيانات الجديدة (بيانات نادي رياضي)
print("📊 Step 1: Loading Gym Data...")
data = {
    'Day': ['Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday', 'Sunday'],
    'New_Members': [5, 3, 8, 2, 10, 15, 4],      # مشتركون جدد
    'Checkins': [50, 40, 60, 45, 80, 120, 30],    # عدد الحضور
    'Cancellations': [1, 0, 2, 1, 0, 3, 1]        # إلغاء الاشتراكات
}
df = pd.DataFrame(data)
data_string = df.to_string(index=False)

# 3. التحليل بالذكاء الاصطناعي (تغيير الـ Prompt)
print("🧠 Step 2: Asking AI to analyze Gym Data...")
prompt = f"""
You are a senior fitness business consultant. 
Review the following weekly gym data:
{data_string}
Write a short executive summary (max 4 sentences). 
Identify the best day for new sign-ups, the busiest day, and a concern about cancellations. 
Provide one strategic recommendation for the gym owner to increase retention.
"""
try:
    response = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[{"role": "user", "content": prompt}],
        max_tokens=200
    )
    ai_summary = response.choices[0].message.content
    print("✅ AI Analysis Complete.")
except Exception as e:
    print(f"❌ AI Error: {e}")
    ai_summary = "AI Analysis failed."

# 4. صناعة تقرير PDF
print("📄 Step 3: Generating PDF...")
pdf = FPDF()
pdf.add_page()

# Title
pdf.set_font('Arial', 'B', 16)
pdf.cell(0, 10, 'Weekly Gym Performance Report', 0, 1, 'C')
pdf.ln(5)

# AI Summary
pdf.set_font('Arial', 'B', 12)
pdf.cell(0, 10, 'AI Consultant Summary:', 0, 1)
pdf.set_font('Arial', '', 11)
pdf.multi_cell(0, 8, ai_summary)
pdf.ln(10)

# Data Table
pdf.set_font('Arial', 'B', 12)
pdf.cell(0, 10, 'Weekly Metrics:', 0, 1)
pdf.set_font('Arial', '', 10)
pdf.set_fill_color(230, 230, 230)

# Table Headers
pdf.cell(35, 10, 'Day', 1, 0, 'C', True)
pdf.cell(40, 10, 'New Members', 1, 0, 'C', True)
pdf.cell(40, 10, 'Check-ins', 1, 0, 'C', True)
pdf.cell(40, 10, 'Cancellations', 1, 1, 'C', True)

# Table Rows
for index, row in df.iterrows():
    pdf.cell(35, 10, str(row['Day']), 1, 0, 'C')
    pdf.cell(40, 10, str(row['New_Members']), 1, 0, 'C')
    pdf.cell(40, 10, str(row['Checkins']), 1, 0, 'C')
    pdf.cell(40, 10, str(row['Cancellations']), 1, 1, 'C')

pdf_filename = 'Gym_Weekly_Report.pdf'
pdf.output(pdf_filename)
print(f"✅ PDF '{pdf_filename}' Generated.")

# 5. إرسال الإيميل
print("✉️ Step 4: Sending Email...")
msg = EmailMessage()
msg['Subject'] = '🏋️ Weekly Gym Report (AI Generated)'
msg['From'] = SENDER_EMAIL
msg['To'] = RECEIVER_EMAIL
msg.set_content("Hello,\n\nPlease find attached the weekly gym performance report generated by AI.\n\nBest regards,\nAutomated System")

# Attach PDF
try:
    with open(pdf_filename, 'rb') as f:
        file_data = f.read()
    msg.add_attachment(file_data, maintype='application', subtype='pdf', filename=pdf_filename)
except FileNotFoundError:
    print("❌ Error: PDF file not found.")

# Send Email
try:
    server = smtplib.SMTP('smtp.gmail.com', 587)
    server.starttls()
    server.login(SENDER_EMAIL, APP_PASSWORD)
    server.send_message(msg)
    server.quit()
    print("🎉 SUCCESS! Gym Report Email sent!")
except Exception as e:
    print(f"❌ Email Error: {e}")
